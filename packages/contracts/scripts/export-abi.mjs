// Generates abi/chainRoll.ts (typed `as const` ABI) and abi/deployments.ts from Foundry output.
// Run via `pnpm --filter @chainroll/contracts build`.
import { existsSync, mkdirSync, readFileSync, readdirSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = join(dirname(fileURLToPath(import.meta.url)), '..')
const outDir = join(root, 'abi')
mkdirSync(outDir, { recursive: true })

const header = '// AUTO-GENERATED by scripts/export-abi.mjs — do not edit.\n'

const artifact = JSON.parse(readFileSync(join(root, 'out/ChainRoll.sol/ChainRoll.json'), 'utf8'))
writeFileSync(
  join(outDir, 'chainRoll.ts'),
  `${header}export const chainRollAbi = ${JSON.stringify(artifact.abi, null, 2)} as const\n`,
)

const printsPath = join(root, 'out/ChainRollPrints.sol/ChainRollPrints.json')
if (existsSync(printsPath)) {
  const printsArtifact = JSON.parse(readFileSync(printsPath, 'utf8'))
  writeFileSync(
    join(outDir, 'chainRollPrints.ts'),
    `${header}export const chainRollPrintsAbi = ${JSON.stringify(printsArtifact.abi, null, 2)} as const\n`,
  )
}

const deployments = {}
const depDir = join(root, 'deployments')
if (existsSync(depDir)) {
  for (const f of readdirSync(depDir).filter((f) => /^\d+\.json$/.test(f) && f !== '31337.json')) {
    const d = JSON.parse(readFileSync(join(depDir, f), 'utf8'))
    deployments[Number(f.replace('.json', ''))] = d.chainRoll
  }
}
writeFileSync(
  join(outDir, 'deployments.ts'),
  `${header}export const chainRollAddress: Partial<Record<number, \`0x\${string}\`>> = ${JSON.stringify(deployments, null, 2)}\n`,
)

console.log(
  `abi: ${artifact.abi.length} entries · deployments: ${Object.keys(deployments).join(', ') || 'none'}`,
)
